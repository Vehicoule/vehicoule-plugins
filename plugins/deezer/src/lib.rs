use bindings::vehicoule::plugin::http;
use bindings::vehicoule::plugin::types::{Artwork, Capability, Domain, Error, Item, ItemKind};

/// The plugin, as the contract sees it.
struct Deezer;

/// The host's `fetch`. Natively the import does not exist, so nothing native calls this: the tests pass a fake. Each
/// export sends its requests with `|r| contract::send(r, host_fetch)`.
fn host_fetch(request: &http::Request) -> Result<http::Response, http::HttpError> {
    http::fetch(request)
}

impl PluginGuest for Deezer {
    fn describe() -> Manifest {
        Manifest {
            // The id is the crate's directory name and the name of the component the build writes
            // (docs/plugin-crates.md); the conformance test checks all three agree.
            id: String::from("deezer"),
            // The service's own name (AGENTS.md rule 16).
            name: String::from("Deezer"),
            version: String::from(env!("CARGO_PKG_VERSION")),
            domains: vec![Domain::Music],
            capabilities: vec![
                Capability::Search,
                Capability::Metadata,
                Capability::Artwork,
                Capability::LinkImport,
            ],
            http_hosts: vec![String::from(request::HOST)],
        }
    }
}

impl SearchGuest for Deezer {
    fn search(query: String, kinds: Vec<ItemKind>, cursor: Option<String>) -> Result<Page, Error> {
        let kinds: Vec<model::ItemKind> = kinds.into_iter().map(contract::kind).collect();
        calls::search(&query, &kinds, cursor.as_deref(), |r| {
            contract::send(r, host_fetch)
        })
        .map(contract::page)
        .map_err(contract::error)
    }

    fn suggest(prefix: String) -> Result<Vec<String>, Error> {
        calls::suggest(&prefix, |r| contract::send(r, host_fetch)).map_err(contract::error)
    }
}

impl MetadataGuest for Deezer {
    fn get_album(id: String) -> Result<AlbumPage, Error> {
        calls::album(&id, |r| contract::send(r, host_fetch))
            .map(contract::album_page)
            .map_err(contract::error)
    }

    fn get_artist(id: String) -> Result<ArtistPage, Error> {
        calls::artist(&id, |r| contract::send(r, host_fetch))
            .map(contract::artist_page)
            .map_err(contract::error)
    }

    fn get_playlist(id: String, cursor: Option<String>) -> Result<PlaylistPage, Error> {
        calls::playlist(&id, cursor.as_deref(), |r| contract::send(r, host_fetch))
            .map(contract::playlist_page)
            .map_err(contract::error)
    }
}

impl ArtworkGuest for Deezer {
    fn find(of: Item) -> Result<Vec<Artwork>, Error> {
        calls::artwork(&contract::artwork_of(&of), |r| {
            contract::send(r, host_fetch)
        })
        .map(contract::artwork)
        .map_err(contract::error)
    }
}

impl LinkImportGuest for Deezer {
    fn import_link(url: String) -> Result<Item, Error> {
        calls::import_link(&url, |r| contract::send(r, host_fetch))
            .map(contract::item)
            .map_err(contract::error)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use bindings::vehicoule::plugin::types::{Artist, Playlist};

    #[test]
    fn describes_itself_as_deezer_with_its_four_capabilities() {
        let manifest = Deezer::describe();
        assert_eq!(manifest.id, "deezer");
        assert_eq!(manifest.name, "Deezer");
        assert_eq!(manifest.version, env!("CARGO_PKG_VERSION"));
        assert_eq!(manifest.domains, vec![Domain::Music]);
        assert_eq!(
            manifest.capabilities,
            vec![
                Capability::Search,
                Capability::Metadata,
                Capability::Artwork,
                Capability::LinkImport
            ]
        );
        assert_eq!(manifest.http_hosts, vec![String::from("api.deezer.com")]);
    }

    // The calls below fail before any request, so the host's `fetch`, which does not exist natively, is never reached;
    // they check that each export runs its call and turns its error into the contract's.

    #[test]
    fn the_exports_refuse_what_cannot_be_asked_before_any_request() {
        assert!(matches!(
            Deezer::suggest(String::from(" ")),
            Err(Error::InvalidInput(_))
        ));
        assert!(matches!(
            Deezer::search(String::new(), Vec::new(), None),
            Err(Error::InvalidInput(_))
        ));
        assert!(matches!(
            Deezer::get_album(String::from("x")),
            Err(Error::InvalidInput(_))
        ));
        assert!(matches!(
            Deezer::get_artist(String::from("x")),
            Err(Error::InvalidInput(_))
        ));
        assert!(matches!(
            Deezer::get_playlist(String::from("1"), Some(String::from("x"))),
            Err(Error::InvalidInput(_))
        ));
        assert!(matches!(
            Deezer::import_link(String::from("https://example.org/track/1")),
            Err(Error::InvalidInput(_))
        ));
        let playlist = Item::Playlist(Playlist {
            id: String::from("1"),
            title: String::from("Mix"),
            owner: None,
            artwork: Vec::new(),
        });
        assert_eq!(Deezer::find(playlist), Err(Error::Unsupported));
        let nameless = Item::Artist(Artist {
            id: String::from("1"),
            name: String::from(" "),
            artwork: Vec::new(),
        });
        assert!(matches!(
            Deezer::find(nameless),
            Err(Error::InvalidInput(_))
        ));
    }
}
