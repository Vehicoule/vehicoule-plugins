//! Search, album, artist and playlist pages, artwork and link import from [Deezer](https://www.deezer.com)'s public
//! API, without an account.
//!
//! The plugin provides `search`, `metadata`, `artwork` and `link-import` (Vehicoule, `docs/plugin-providers.md`,
//! section 2, with ADR 0018). It keeps nothing between calls, never retries, and reaches only `api.deezer.com`.
//!
//! The code is split as every plugin's is (docs/plugin-crates.md, section 2): [`request`] builds the requests from a
//! call's arguments, [`read`] reads the answers into [`model`]'s types, [`link`] reads a pasted link, and the calls
//! run them with the `fetch` they are given, which is the host's in the component and a fake in the tests.
//!
//! # Service
//!
//! Everything the plugin relies on was checked on 2026-11-07 by calling `https://api.deezer.com` from a cloud
//! container, without an account, once per request below, and reading the answer: one call each, not a measurement.
//! Deezer's API documentation (`https://developers.deezer.com/api`) answered with a redirect to a login page, so
//! nothing here comes from it.
//!
//! - Every answer, errors included, had status `200` and `Content-Type: application/json; charset=utf-8`. An error is
//!   an object `{"error":{"type":…,"message":…,"code":…}}`: code `800` (`DataException`, `no data`) for an unknown
//!   track, artist or album (`/track/999999999999`, `/artist/0`, `/album/abc`, `/track/-1`), which the plugin reads
//!   as not found; code `600` (`InvalidQueryException`) for an unknown path and code `500` (`ParameterException`,
//!   `empty parameter`) for an empty query, which it reads, like any other code, as upstream. Not seen: a rate
//!   limit's answer; the plugin reads a `429` as rate-limited with its `Retry-After`, and any other error as upstream.
//! - `GET /search?q=…&index=…&limit=…` returns `{"data":[track…],"total":…,"next":…}`, `next` only while there is a
//!   next page (`/search?q=daft&index=99999` had none); `/search/album`, `/search/artist` and `/search/playlist` the
//!   same with albums, artists and playlists. 25 results came back without `limit`; `limit=1000` gave 100.
//! - `GET /search/autocomplete?q=…&index=…&limit=…` returns `tracks`, `albums`, `artists`, `playlists` (and
//!   `podcasts`, `radios`, which the plugin ignores), each `{"data":[…]}`, with `next` at the top: `limit=5` gave up
//!   to 5 of each kind, and `index=10` the next ones of each. Its tracks have no `isrc`.
//! - A track (`/track/{id}`, `/track/isrc:{isrc}`, in searches and lists) has `id` (an integer), `title` (with its
//!   version), `title_short` (without it), `duration` (seconds), `isrc` (not in the autocomplete's or an album's
//!   embedded tracks), `artist` (`id`, `name`), `contributors` (a list of artists, in `/track/{id}` and an artist's top
//!   tracks) and `album` (`id`, `title`, covers; absent from `/album/{id}/tracks`).
//! - An album (`/album/{id}`) has `id`, `title`, `release_date` (`YYYY-MM-DD`), `artist`, `contributors`,
//!   `nb_tracks` and covers, and embeds its tracks in `tracks.data`: 25 of 100 by default, `limit` of them with
//!   `limit`. `/album/{id}/tracks?limit=1000` returned all 100 tracks of an album of 100, with their ISRCs.
//! - An artist (`/artist/{id}`) has `id`, `name` and pictures; `/artist/{id}/top?limit=…` returns tracks and
//!   `/artist/{id}/albums?limit=…` albums, without `artist`.
//! - A playlist (`/playlist/{id}`) has `id`, `title`, `nb_tracks`, `creator` (`name`; `user` in searches) and
//!   pictures, and embeds its tracks, with their ISRCs, in `tracks.data`: 400 of 1000 by default (591,398 bytes);
//!   with `?index=500&limit=3`, the 3 tracks from the 501st, the same as `/playlist/{id}/tracks?index=500&limit=3`.
//! - Covers (`cover_small`, `cover_medium`, `cover_big`, `cover_xl`) and pictures (`picture_*`) are `https` URLs on
//!   `cdn-images.dzcdn.net` whose path names their size: 56×56, 250×250, 500×500 and 1000×1000. `cover` and `picture`
//!   point back to `api.deezer.com` and are not used.
//! - A link to a Deezer page is `https://www.deezer.com/{language}/{kind}/{id}`, which answered `200` for
//!   `/fr/track/3135556`. A short link of `link.deezer.com` answered with a redirect (`302`); the plugin does not
//!   follow it.
//! - Search operators (`artist:"…"`, `track:"…"`, `album:"…"`) gave no result for *Get Lucky* by Daft Punk, or
//!   results unrelated to the artist: the plugin searches with plain words.
//!
//! Not checked: Deezer's rate limit and its terms of use, whose pages need a Deezer account (Vehicoule's plugin
//! providers, section 4); how Deezer answers a rate limit; ids other than positive integers.

