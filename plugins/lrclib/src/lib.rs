//! Lyrics from [LRCLIB](https://lrclib.net), a free and open lyrics database: synced lyrics when it has them, plain
//! lyrics otherwise.
//!
//! The plugin provides one capability, `lyrics` (Vehicoule, `docs/plugin-providers.md`, section 2). For a track, it
//! asks LRCLIB for the record that matches the track's title, artists, album and duration, with one request, and
//! returns the record's synced lyrics, read from their LRC text ([`lrc`]), or its plain lyrics. It keeps nothing
//! between calls, never retries, and reaches only `lrclib.net`.
//!
//! The code is split as every plugin's is (docs/plugin-crates.md, section 2): [`request`] builds the request from the
//! track, [`response`] reads the answer, and `find` runs the two with the `fetch` function it is given, which is the
//! host's in the component and a fake in the tests.
//!
//! # Service
//!
//! Everything the plugin relies on, each checked on 2026-11-07 from a cloud container, without an account: by reading
//! LRCLIB's API documentation (`https://lrclib.net/docs.txt`, linked from `https://lrclib.net/llms.txt`), and by one
//! call of each request below, reading the answer. One call each, not a measurement.
//!
//! - `GET https://lrclib.net/api/get` with `track_name` and `artist_name` (required), `album_name` and `duration`
//!   (optional; documentation, section "Get lyrics with a track's signature"). The documentation says the duration, in
//!   seconds, must be between 1 and 3600, and that a record matches only within ±2 seconds of it. A call for
//!   *Get Lucky* with `artist_name` `Daft Punk`, then `Daft Punk, Pharrell Williams`, then
//!   `Daft Punk & Pharrell Williams`, and `duration=248`, returned the same record each time, whose `artistName` is
//!   `Daft Punk, Pharrell Williams`: the plugin sends every artist of the track, joined with `, `.
//! - `200` with `Content-Type: application/json` and one record, an object with (documentation, section "Lyrics record
//!   fields", and the calls): `instrumental` (boolean), `plainLyrics` and `syncedLyrics` (string or `null`; `null` for
//!   an instrumental record; a call to `/api/search?q=still+alive+portal` returned 20 records, 5 with `syncedLyrics`
//!   `null` and `plainLyrics` set), and `duration` (seconds, a number with a fraction in some records, such as
//!   `152.137167`), which the plugin does not read.
//! - `syncedLyrics` is LRC text: one line per lyric line, each starting with a time tag `[mm:ss.xx]`; the record's last
//!   line is a time tag with no text, which marks the end of the last line (the documentation's example ends with
//!   `[03:25.72] `, and so did all 15 synced records of the search above). Every line of those 15 records starts with
//!   one or more time tags of 2 minute digits, 2 second digits and 1 to 3 digits of fraction. How [`lrc`] reads the
//!   other forms LRC allows is said there.
//! - `404` with `{"message":"Failed to find specified track","name":"TrackNotFound","statusCode":404}` when no record
//!   matches (documentation, section "Errors", and a call for an unknown artist and title).
//! - `429` (`RateLimitExceeded`) and `503` (`ServerOverloaded`) come with `Retry-After`, a number of seconds, and the
//!   documentation asks clients to wait that long ("Honor `Retry-After` on `429` and `503` responses", `llms.txt`);
//!   both become the contract's `rate-limited` with that delay. Not called: the plugin cannot make LRCLIB answer them.
//! - A request missing a required parameter gets a plain-text answer that is not JSON (documentation, section
//!   "Errors"; a call without `artist_name` returned `Failed to deserialize query string: missing field
//!   artist_name`): the plugin never sends one ([`request`] refuses a track without a title or an artist), and reads
//!   any status but `200`, `404`, `429` and `503` as `upstream`.
//! - The documentation requires clients to name themselves in `User-Agent`, with a version and a link, and says the
//!   allowance is about 90 requests per minute per IP address for a client that does, about 45 for one that does not
//!   (section "Rate Limiting", "approximations of the current settings and may change at any time"). The plugin sends
//!   `User-Agent: vehicoule-lrclib/<version> (https://github.com/Vehicoule/vehicoule-plugins)`.
//!
//! Not checked: LRCLIB's terms of use, which the documentation does not link to; how often a track of Deezer or iTunes
//! has a record in LRCLIB, which needs a sample of real tracks.

pub mod lrc;
pub mod request;
