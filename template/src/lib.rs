//! The crate a new plugin starts from (docs/plugin-crates.md).
//!
//! It implements only what every plugin must: `describe`, from the contract's `base` world. It provides no capability
//! and declares no HTTP host, so it can reach nothing. CI builds it to a component and installs it in Vehicoule's
//! plugin host like any plugin, so the build, the bindings and the conformance test are checked before the first
//! real plugin exists. It is never published.
//!
//! A plugin made from it renames the crate to `vehicoule-plugin-<id>`, sets its manifest, and changes `world` to the
//! capability worlds it provides (`search-plugin`, `metadata-plugin`, ...), or to a world of its own that includes
//! them.

/// The guest side of the contract in `wit/`, generated by `wit-bindgen`.
///
/// The only module where `unsafe` is allowed, because the generated code needs it (ADR 0005). Nothing is written by
/// hand here but the macro calls. The exports are linked only for Wasm: natively, the tests call the plugin's
/// functions directly.
#[cfg_attr(
    target_arch = "wasm32",
    expect(
        unsafe_code,
        reason = "the exports wit-bindgen generates are `unsafe` (ADR 0005)"
    )
)]
#[expect(
    clippy::same_length_and_capacity,
    reason = "in the code wit-bindgen generates (ADR 0005)"
)]
mod bindings {
    wit_bindgen::generate!({ path: "../wit", world: "vehicoule:plugin/base@0.1.0" });

    #[cfg(target_arch = "wasm32")]
    use super::Template;
    #[cfg(target_arch = "wasm32")]
    export!(Template);
}

use bindings::exports::vehicoule::plugin::plugin::{Guest, Manifest};
use bindings::vehicoule::plugin::types::Domain;

/// The plugin, as the contract sees it.
struct Template;

impl Guest for Template {
    fn describe() -> Manifest {
        Manifest {
            // The id is the crate's directory name and the name of the component the build writes
            // (docs/plugin-crates.md); the conformance test checks all three agree.
            id: String::from("template"),
            name: String::from("Template"),
            version: String::from(env!("CARGO_PKG_VERSION")),
            domains: vec![Domain::Music],
            capabilities: Vec::new(),
            http_hosts: Vec::new(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use bindings::vehicoule::plugin::types::Capability;

    #[test]
    fn describes_itself_with_the_crate_version() {
        let manifest = Template::describe();
        assert_eq!(manifest.id, "template");
        assert_eq!(manifest.name, "Template");
        assert_eq!(manifest.version, env!("CARGO_PKG_VERSION"));
        assert_eq!(manifest.domains, vec![Domain::Music]);
    }

    #[test]
    fn provides_nothing_and_reaches_no_host() {
        let manifest = Template::describe();
        assert_eq!(manifest.capabilities, Vec::<Capability>::new());
        assert_eq!(manifest.http_hosts, Vec::<String>::new());
    }
}
